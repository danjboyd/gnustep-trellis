#!/usr/bin/env python3
"""Builds Work-virtual.trellis and Work-virtual.sample.json from
Work.trellis: the same detail panel and styles, with the wall as a
<virtual layout="grid"> of 2,000 made-up agents in four groups.
Run from this directory: python3 -I gen-virtual.py"""
import json, re

src = open('Work.trellis').read()
start = src.index('<scroll id="wallScroll"')
end = src.index('</scroll>', start) + len('</scroll>')
focus = src[src.index('<column id="focus"'):src.index('<label class="group"')].rstrip()
# The Focus strip becomes the first item: no outlets inside a template.
focus = re.sub(r' id="[^"]*"', '', focus)
focus = focus.replace('<column class="focus">', '<column class="focus">', 1)
focus = '\n'.join('      ' + l.strip() if i else l.strip() for i, l in enumerate(focus.splitlines()))

def tile(state, extra_top='', extra=''):
    status_cls = 'status needs-text grow' if state == 'needs' else 'status muted grow'
    return f'''      <template id="tile-{state}">
        <row class="tile">
          <box class="bar {state}"></box>
          <column class="tile-body">
            <row class="tile-row"><text id="name" class="name grow">agent</text>{extra_top}</row>
            <row class="tile-row"><text id="status" class="{status_cls}">status</text><text id="where" class="muted small where">host · harness</text></row>
{extra}            <text id="headline" class="headline">headline</text>
            <text id="foot" class="foot">foot</text>
          </column>
        </row>
      </template>'''

pill = '<box class="pill"><label id="pill" class="pill-text">acct</label></box>'
badges = '            <text id="badges" class="badges">badges</text>\n'
virtual = f'''<virtual id="wall" layout="grid" template="tile-working" estimated-size="120">
      <template id="focus">
      {focus}
      </template>
      <template id="group"><label id="groupTitle" class="group">Group</label></template>
{tile("needs", pill, badges)}
{tile("working")}
{tile("idle")}
{tile("stopped", "", badges)}
    </virtual>'''

out = src[:start] + virtual + src[end:]
out = out.replace('''<!-- AIManager's Work tab as a Trellis spec: the proposal.''',
'''<!-- GENERATED by gen-virtual.py from Work.trellis: edit that, then rerun.
     The wall as a <virtual layout="grid">: only the tiles on screen have
     views (Trellis 0.4). The Focus strip is the first item and group
     headers are items, both a whole row wide. -->
<!-- AIManager's Work tab as a Trellis spec: the proposal.''', 1)
out = out.replace('  .wallscroll { flex: 1; min-height: 0; }\n  .wall       { gap: 10px; padding: 12px; }\n',
'  #wall      { flex: 1; min-height: 0; grid-template-columns: repeat(auto-fill, minmax(230px, 1fr));\n'
'               gap: 10px; padding: 12px; }\n', 1)
out = out.replace('  .focus      { gap: 10px;', '  .focus      { grid-column: 1 / -1; gap: 10px;', 1)
out = out.replace('  .group      { color: GrayText; font-weight: bold; margin-top: 6px; }',
                  '  .group      { grid-column: 1 / -1; color: GrayText; font-weight: bold; padding-top: 6px; }', 1)
out = out.replace('  .tiles      { display: grid; grid-template-columns: repeat(auto-fill, minmax(230px, 1fr)); gap: 10px; }\n', '', 1)
assert 'wallScroll' not in out
open('Work-virtual.trellis', 'w').write(out)

hosts = ['host-1 · claude', 'host-2 · claude', 'host-3 · codex']
heads = ['Linking the installer; the other packages are done.',
         'Draft of the migration section is up for review, with two open questions about the old settings format.',
         '412 of 980 tests done, no failures so far.',
         'Refactoring the sync client.']
sample = {"wall": {"items": [
    {"_template": "focus"},
    {"_template": "group", "groupTitle": "Needs you (12)"},
    {"_repeat": 4, "items": [
        {"_template": "tile-needs", "name": "agent-n{n:2}", "pill": "acct-2 82%",
         "status": "needs you: pick the release channel", "where": hosts[0], "badges": "ask open",
         "headline": "Ship as beta or stable? Both builds pass; beta keeps the old updater one more week.",
         "foot": "Manager: answer before the 3 pm build"},
        {"_template": "tile-needs", "name": "agent-n{n:2}", "pill": "acct-1 40%",
         "status": "needs you: approve the plan", "where": hosts[1], "badges": "plan waiting",
         "headline": "Plan ready: three steps, no schema change.", "foot": "Today 0/2 · Plan sign-off"},
        {"_template": "tile-needs", "name": "agent-n{n:2}", "pill": "acct-3 91%",
         "status": "needs you: a hands-on check", "where": hosts[2], "badges": "2 unread",
         "headline": "Please click through the new settings screen once.", "foot": "Today 1/3 · Settings screen"}]},
    {"_template": "group", "groupTitle": "Working (1,400)"},
    {"_repeat": 350, "items": [
        {"_template": "tile-working", "name": "build-{n:4}", "status": "building the candidate", "where": hosts[i % 3],
         "headline": heads[i], "foot": "Today 2/5 · Ship the candidate"} for i in range(4)]},
    {"_template": "group", "groupTitle": "Idle (500)"},
    {"_repeat": 250, "items": [
        {"_template": "tile-idle", "name": "helper-{n:3}", "status": "idle since 10:40", "where": hosts[1],
         "headline": "Finished the settings screen; waiting for the next item.", "foot": "Keeps Project Beta's UI moving"},
        {"_template": "tile-idle", "name": "helper-{n:3}", "status": "idle since 09:15", "where": hosts[2],
         "headline": "Weekly numbers exported.", "foot": "Exports and checks the weekly reports"}]},
    {"_template": "group", "groupTitle": "Stopped (88)"},
    {"_repeat": 88, "items": [
        {"_template": "tile-stopped", "name": "worker-{n:2}", "status": "stopped", "where": hosts[0],
         "badges": "session ended", "headline": "Last run ended cleanly.", "foot": "Owns Project Gamma's sync service"}]},
]}}
json.dump(sample, open('Work-virtual.sample.json', 'w'), indent=1, ensure_ascii=False)
open('Work-virtual.sample.json', 'a').write('\n')
print('wrote Work-virtual.trellis and Work-virtual.sample.json')
