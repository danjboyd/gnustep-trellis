#!/usr/bin/env python3
"""Record conformance results per platform and regenerate the README table.

    scripts/conformance-summary.py record --platform macos --runner build/trellis-case
    scripts/conformance-summary.py record --platform linux --runner obj/trellis-case
    scripts/conformance-summary.py table            # rewrite the README block
    scripts/conformance-summary.py table --check    # exit 1 if README is stale
    scripts/conformance-summary.py check --platform linux --runner obj/trellis-case
                                                    # exit 1 if any suite passes
                                                    # fewer cases than recorded (CI gate)

`record` runs trellis-case over Tests/Engine/cases and Tests/Conformance/cases
and writes docs/conformance/<platform>.json (commit, date, per-suite
pass/total, skips). `table` renders both platforms into README.md between
the conformance-table markers, so the numbers are never edited by hand.
A platform recorded at a different commit than the other is labelled with
its own commit, so a stale column is visible.

Copyright (C) 2026 Dan Boyd. Licensed under the GNU LGPL, version 2.1 or later.
"""
import argparse
import datetime
import json
import os
import re
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
DATA = os.path.join(ROOT, "docs", "conformance")
README = os.path.join(ROOT, "README.md")
BEGIN = "<!-- conformance-table:begin (generated by scripts/conformance-summary.py; do not edit) -->"
END = "<!-- conformance-table:end -->"
PLATFORMS = [("linux", "Linux (GNUstep)"), ("macos", "macOS (Cocoa)")]
SUITES = [  # (suite, source description); unknown suites are appended
    ("engine", "hand-written, `Tests/Engine/cases`"),
    ("yoga", "facebook/yoga gentest"),
    ("wpt", "web-platform-tests css-flexbox (check-layout)"),
    ("wpt-grid", "web-platform-tests css-grid (check-layout)"),
    ("wpt-sizing", "web-platform-tests css-sizing (check-layout)"),
]

SUITE_RE = re.compile(r"^\s+([\w.-]+):\s+(\d+)/(\d+)")
TOTAL_RE = re.compile(r"^PASS (\d+)/(\d+).*?skip (\d+)")


def git(*args):
    return subprocess.run(["git", "-C", ROOT] + list(args), capture_output=True,
                          text=True, check=True).stdout.strip()


def run_cases(runner, path):
    p = subprocess.run([runner, path], capture_output=True, text=True, cwd=ROOT)
    suites, total = {}, None
    for line in p.stdout.splitlines():
        m = TOTAL_RE.match(line)
        if m:
            total = {"pass": int(m.group(1)), "total": int(m.group(2)),
                     "skipped": int(m.group(3))}
            continue
        m = SUITE_RE.match(line)
        if m and total is not None:
            suites[m.group(1)] = {"pass": int(m.group(2)), "total": int(m.group(3))}
    if total is None:
        sys.exit("conformance-summary: no PASS line from %s %s:\n%s%s"
                 % (runner, path, p.stdout[-2000:], p.stderr[-2000:]))
    return suites, total


def count_cases(path):
    n = {}
    base = os.path.join(ROOT, path)
    for d in sorted(os.listdir(base)) if os.path.isdir(base) else []:
        full = os.path.join(base, d)
        if os.path.isdir(full):
            n[d] = sum(1 for _, _, fs in os.walk(full) for f in fs if f.endswith(".json"))
    return n


def record(args):
    suites, _ = run_cases(args.runner, "Tests/Engine/cases")
    conf, total = run_cases(args.runner, "Tests/Conformance/cases")
    suites.update(conf)
    counts = count_cases("Tests/Conformance/cases")
    for s, n in counts.items():
        if s in suites:
            suites[s]["cases"] = n
    dirty = bool(git("status", "--porcelain", "--untracked-files=no", "--", "Source", "Tests", "Tools"))
    data = {
        "platform": args.platform,
        "commit": git("rev-parse", "--short", "HEAD") + ("+dirty" if dirty else ""),
        "date": datetime.date.today().isoformat(),
        "suites": suites,
        "conformance": total,
    }
    os.makedirs(DATA, exist_ok=True)
    out = os.path.join(DATA, args.platform + ".json")
    with open(out, "w") as f:
        json.dump(data, f, indent=1, sort_keys=True)
        f.write("\n")
    print("recorded %s at %s: conformance %d/%d, skipped %d"
          % (args.platform, data["commit"], total["pass"], total["total"], total["skipped"]))


def check(args):
    """CI gate: fail if any suite passes fewer cases than this platform's
    recorded results (docs/conformance/<platform>.json)."""
    path = os.path.join(DATA, args.platform + ".json")
    with open(path) as f:
        rec = json.load(f)
    suites, _ = run_cases(args.runner, "Tests/Engine/cases")
    conf, _ = run_cases(args.runner, "Tests/Conformance/cases")
    suites.update(conf)
    bad = []
    for s, r in sorted(rec["suites"].items()):
        now = suites.get(s)
        if now is None:
            bad.append("%s: missing from this run" % s)
        elif now["pass"] < r["pass"]:
            bad.append("%s: %d/%d passing, recorded %d/%d at %s"
                       % (s, now["pass"], now["total"], r["pass"], r["total"], rec["commit"]))
        print("%-10s %d/%d (recorded %d/%d)" % (s, now["pass"] if now else 0,
              now["total"] if now else 0, r["pass"], r["total"]))
    if bad:
        print("conformance regression:\n  " + "\n  ".join(bad))
        sys.exit(1)
    print("conformance: no regression against %s @ %s" % (args.platform, rec["commit"]))


def cell(r):
    if not r:
        return "n/a"
    s = "%d/%d" % (r["pass"], r["total"])
    if r["total"] and r["pass"] != r["total"]:
        s += " (%.1f%%)" % (100.0 * r["pass"] / r["total"])
    return s


def render():
    recs = {}
    for p, _ in PLATFORMS:
        path = os.path.join(DATA, p + ".json")
        if os.path.exists(path):
            with open(path) as f:
                recs[p] = json.load(f)
    if not recs:
        sys.exit("conformance-summary: nothing recorded in docs/conformance/")
    commits = {r["commit"] for r in recs.values()}
    heads = []
    for p, label in PLATFORMS:
        r = recs.get(p)
        if r and len(commits) > 1:
            label += " @ %s" % r["commit"]
        heads.append(label)
    names = [s for s, _ in SUITES]
    for r in recs.values():
        names += [s for s in r["suites"] if s not in names]
    src = dict(SUITES)
    lines = ["| Suite | Source | " + " | ".join(heads) + " |",
             "|---|---|" + "---|" * len(heads)]
    for s in names:
        cases = next((r["suites"][s].get("cases") for r in recs.values()
                      if s in r["suites"] and r["suites"][s].get("cases")), None)
        desc = src.get(s, "")
        if cases:
            desc += ", %d cases" % cases
        lines.append("| %s | %s | %s |" % (s, desc, " | ".join(
            cell(recs.get(p, {}).get("suites", {}).get(s)) for p, _ in PLATFORMS)))
    lines.append("| **all conformance** | | %s |" % " | ".join(
        "**%s**" % cell(recs[p]["conformance"]) if p in recs else "n/a" for p, _ in PLATFORMS))
    skipped = sorted({recs[p]["conformance"]["skipped"] for p in recs})
    when = ", ".join("%s %s (%s)" % (dict(PLATFORMS)[p].split(" ")[0], recs[p]["commit"], recs[p]["date"])
                     for p, _ in PLATFORMS if p in recs)
    lines.append("")
    lines.append("Recorded: %s. Skipped by `requires` tag: %s." %
                 (when, " / ".join(str(s) for s in skipped)))
    return "\n".join(lines)


def table(args):
    with open(README) as f:
        text = f.read()
    if BEGIN not in text or END not in text:
        sys.exit("conformance-summary: README.md has no conformance-table markers")
    pre, rest = text.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    new = pre + BEGIN + "\n" + render() + "\n" + END + post
    if args.check:
        if new != text:
            print("README.md conformance table is stale; run scripts/conformance-summary.py table")
            sys.exit(1)
        print("README.md conformance table is current")
        return
    if new != text:
        with open(README, "w") as f:
            f.write(new)
        print("README.md conformance table updated")
    else:
        print("README.md conformance table already current")


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    r = sub.add_parser("record")
    r.add_argument("--platform", required=True, choices=[p for p, _ in PLATFORMS])
    r.add_argument("--runner", required=True)
    t = sub.add_parser("table")
    t.add_argument("--check", action="store_true")
    c = sub.add_parser("check")
    c.add_argument("--platform", required=True, choices=[p for p, _ in PLATFORMS])
    c.add_argument("--runner", required=True)
    args = ap.parse_args()
    {"record": record, "table": table, "check": check}[args.cmd](args)


if __name__ == "__main__":
    main()
